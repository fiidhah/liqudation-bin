const express = require("express");
const router = express.Router();

const {
    getAllDailyPrices,
    getTodayPrices,
    getProductDailyPrices,
    addDailyPrice,
    updateDailyPrice,
    saveProductWeeklyPrices,
    deleteDailyPrice,
    applyTodayPrices,
    autoGenerateDailyPrices
} = require("../controllers/dailyPriceController");

// Get all daily price configurations
router.get("/", getAllDailyPrices);

// Get today's active price overrides
router.get("/today", getTodayPrices);

// Get 7-day daily prices for a specific product
router.get("/product/:id", getProductDailyPrices);

// Save full 7-day schedule for a product
router.post("/save-weekly", saveProductWeeklyPrices);

// Add / Upsert a daily price configuration for a product
router.post("/add", addDailyPrice);

// Auto-generate 7-day liquidation prices for all products
router.post("/generate-all", autoGenerateDailyPrices);

// Update a daily price entry
router.put("/update/:id", updateDailyPrice);

// Delete a daily price entry
router.delete("/delete/:id", deleteDailyPrice);

// Trigger bulk apply of today's prices to products
router.post("/apply-today", applyTodayPrices);

module.exports = router;
